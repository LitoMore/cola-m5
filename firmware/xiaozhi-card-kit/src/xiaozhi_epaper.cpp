bool XiaozhiEpaper::begin() {
  pinMode(kPinCs, OUTPUT);
  pinMode(kPinDc, OUTPUT);
  pinMode(kPinReset, OUTPUT);
  pinMode(kPinBusy, INPUT);
  digitalWrite(kPinCs, HIGH);
  digitalWrite(kPinDc, HIGH);

  spi_.begin(kPinSck, -1, kPinMosi, kPinCs);
  hardwareReset();
  fillScreen(0xFFFF);
  ready_ = true;
  return true;
}

int XiaozhiEpaper::width() const {
  return kWidth;
}

int XiaozhiEpaper::height() const {
  return kHeight;
}

void XiaozhiEpaper::waitDisplay() {
  waitBusy(3000);
}

void XiaozhiEpaper::startWrite() {
}

void XiaozhiEpaper::endWrite() {
}

void XiaozhiEpaper::display() {
  if (!ready_) {
    return;
  }

  setWindow(0, 0, kWidth, kHeight);
  sendCommand(0x24);
  sendData(buffer_, sizeof(buffer_));

  uint8_t refreshMode = firstRefresh_ ? kFullRefresh : kPartialRefresh;
  if (triggerRefresh(refreshMode)) {
    firstRefresh_ = false;
  }
}

void XiaozhiEpaper::fillScreen(uint16_t color) {
  memset(buffer_, isInkColor(color) ? 0xFF : 0x00, sizeof(buffer_));
}

void XiaozhiEpaper::drawFastHLine(int32_t x, int32_t y, int32_t w, uint16_t color) {
  bool ink = isInkColor(color);
  for (int32_t dx = 0; dx < w; ++dx) {
    drawPixel(x + dx, y, ink);
  }
}

void XiaozhiEpaper::drawRoundRect(int32_t x, int32_t y, int32_t w, int32_t h, int32_t, uint16_t color) {
  bool ink = isInkColor(color);
  drawFastHLine(x, y, w, color);
  drawFastHLine(x, y + h - 1, w, color);
  drawVLine(x, y, h, ink);
  drawVLine(x + w - 1, y, h, ink);
}

